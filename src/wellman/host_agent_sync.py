"""Version-stamped WellManifest standards SSOT and LLM host instruction sync.

Generates ``STANDARDS.md`` and ``AGENT-INVARIANTS.md`` from ``wellman.registry``
(augmented by ``repos.manifest`` when present) and synchronizes a compact,
unpinned SSOT + hard workspace invariants block into every non-git LLM host
and workspace instruction file whenever ``wellman`` upgrades to a new version.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

from wellman import __version__ as WELLMAN_VERSION
from wellman.registry import list_standards

START_PREFIX = "<!-- wellmanifest:standards-ssot:start"
END_MARK = "<!-- wellmanifest:standards-ssot:end -->"
_BLOCK_RE = re.compile(
    r"<!-- wellmanifest:standards-ssot:start(?:\s+wellman-version=([0-9A-Za-z._+-]+))?\s*-->"
    r".*?"
    r"<!-- wellmanifest:standards-ssot:end -->\n?",
    re.DOTALL,
)
_VERSION_RE = re.compile(
    r"<!-- wellmanifest:standards-ssot:start\s+wellman-version=([0-9A-Za-z._+-]+)\s*-->"
)


def _first_readme_summary(repo_dir: Path) -> str:
    for name in ("README.md", "readme.md"):
        candidate = repo_dir / name
        if not candidate.is_file():
            continue
        try:
            for raw in candidate.read_text(encoding="utf-8", errors="ignore").splitlines():
                line = raw.strip()
                if not line or line.startswith(("#", "<!--", "![", "[![")):
                    continue
                if line.startswith(">"):
                    line = line.lstrip("> ").strip()
                if len(line) >= 12:
                    return line[:110].rstrip(".") + ("..." if len(line) > 110 else "")
        except OSError:
            pass
    return ""


def _normalize_standard_name(raw: str) -> str:
    name = raw.strip().strip("/")
    while name.startswith("wellmanifest/"):
        name = name[len("wellmanifest/"):].strip("/")
    return name


def collect_standards(wellmanifest_root: Path) -> list[dict[str, str]]:
    """Collect standards from wellman.registry and optional repos.manifest."""
    by_name: dict[str, dict[str, str]] = {}

    for pack in list_standards():
        raw_name = getattr(pack, "id", None) or getattr(pack, "name", "")
        name = _normalize_standard_name(str(raw_name))
        if not name or "/" in name:
            continue
        repo_dir = wellmanifest_root / name
        desc = getattr(pack, "description", "") or getattr(pack, "summary", "") or ""
        by_name[name] = {
            "name": name,
            "local_exists": "yes" if repo_dir.is_dir() else "no",
            "local_path": str(repo_dir),
            "github_url": f"https://github.com/wellmanifest/{name}",
            "notes": desc.strip() or "WellManifest standard repository",
        }

    manifest_path = wellmanifest_root / "repos.manifest"
    if manifest_path.is_file():
        for raw in manifest_path.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            parts = raw.split("\t")
            name = _normalize_standard_name(parts[0])
            if not name or name == ".github" or "/" in name:
                continue
            notes = parts[5].strip() if len(parts) > 5 else ""
            repo_dir = wellmanifest_root / name
            if not notes and repo_dir.is_dir():
                notes = _first_readme_summary(repo_dir)
            existing = by_name.get(name)
            by_name[name] = {
                "name": name,
                "local_exists": "yes" if repo_dir.is_dir() else "no",
                "local_path": str(repo_dir),
                "github_url": f"https://github.com/wellmanifest/{name}",
                "notes": notes or (existing["notes"] if existing else "WellManifest standard repository"),
            }

    return [by_name[k] for k in sorted(by_name)]


def render_standards_index(
    rows: list[dict[str, str]],
    *,
    wellmanifest_root: Path,
    version: str,
) -> str:
    """Render the live, unpinned STANDARDS.md index."""
    manifest_ref = wellmanifest_root / "repos.manifest"
    lines = [
        "# WellManifest Live Standards Index (SSOT)",
        "",
        f"> Auto-generated by `wellman` `{version}` (`python -m wellman.host_agent_sync`).",
        f"> Source: `wellman.registry` + `{manifest_ref}`.",
        "> **Zero pinned standard versions or stale SHAs.** Always read the live `README.md` / `docs/` from the local checkout or GitHub `main`.",
        "",
        "## Hard workspace & storage invariants (applies to every LLM)",
        "- **NEVER** create project worktrees, git clones, scratch checkouts, or ad-hoc task/audit folders under `~/.local/state`, `~/.local/share`, or `/tmp`.",
        "- **ALWAYS** place delivery worktrees inside the owning repository's primary checkout at `<primary>/.worktrees/ticket-NNN--description` (branch `ticket/NNN-description`, allocated via `./project/new-ticket.sh`).",
        "- **ALWAYS** keep operational logs, scratch data, and recovery evidence inside the owning repository's ignored `<primary>/.subactor/recovery/` — never invent new top-level directories in `~/.local/`.",
        "- **ALWAYS** deliver final reports/plans under `docs/` per `wellmanifest/docs` and run `./project/governance-check.sh` + `wellman check`.",
        "",
        "## How every LLM agent must resolve standards",
        "1. Look up the relevant standard name in the table below (or in `repos.manifest`).",
        f"2. Read the **live specification** directly from `{wellmanifest_root}/<name>/README.md` (or `https://github.com/wellmanifest/<name>`).",
        "3. Ignore older version numbers or commit SHAs pasted into legacy prose unless a repository's `.governance/manifest.lock.json` explicitly pins them.",
        "4. Run `wellman check` inside the target repository to verify adopted standards.",
        "",
        f"## All `wellmanifest/*` repositories ({len(rows)})",
        "",
        "| Standard | Local checkout | GitHub (live `main`) | Purpose |",
        "| --- | --- | --- | --- |",
    ]
    for row in rows:
        local_cell = f"`{row['local_path']}`" if row["local_exists"] == "yes" else "_not checked out locally_"
        notes = row["notes"].replace("|", "\\|")
        lines.append(f"| **{row['name']}** | {local_cell} | {row['github_url']} | {notes} |")
    lines.append("")
    return "\n".join(lines)


def build_ssot_block(
    *,
    workspace_root: Path,
    wellmanifest_root: Path,
    version: str,
    full_links: bool,
) -> str:
    """Render the managed, version-stamped SSOT + invariants block."""
    standards_md = wellmanifest_root / "STANDARDS.md"
    manifest_path = wellmanifest_root / "repos.manifest"
    start_mark = f"{START_PREFIX} wellman-version={version} -->"
    body = [
        start_mark,
        f"## WellManifest live standards catalog (SSOT — managed by wellman {version})",
        "",
        "Never rely on stale version numbers or commit SHAs pasted in older prose.",
        f"Always read the **live current specification** directly from `{wellmanifest_root}/<name>`",
        "or GitHub `https://github.com/wellmanifest/<name>`:",
        "",
        "- **Hard workspace & storage invariants (MUST / NEVER — applies to ALL LLMs):**",
        "  - **NEVER** create project worktrees, git clones, scratch checkouts, or ad-hoc task/audit folders under `~/.local/state`, `~/.local/share`, or `/tmp`.",
        "  - **ALWAYS** put delivery worktrees inside the owning repo at `<primary>/.worktrees/ticket-NNN--description` (branch `ticket/NNN-description`, allocated via `./project/new-ticket.sh`).",
        "  - **ALWAYS** put operational logs/recovery inside the owning repo's ignored `<primary>/.subactor/recovery/` (never invent new top-level folders in `~/.local/`), and final reports under `docs/`.",
        "- **Complete LLM-readable index of all `wellmanifest/*` standards:**",
        f"  - Index: `{standards_md}` (generated from `wellman.registry` + `{manifest_path}`)",
        "  - GitHub: `https://github.com/wellmanifest` · `https://github.com/wellmanifest/.github/blob/main/profile/README.md`",
        "- **Resolution protocol (Claude, Codex, Gemini, Cursor, OpenCode, Windsurf, Copilot, Droid, Aider, Continue, Cline, local LLMs):**",
        f"  1. Consult `{standards_md}` to locate the exact standard.",
        f"  2. Read `{wellmanifest_root}/<name>/README.md` (or `docs/`) directly for current rules.",
        "  3. Run `wellman check` in the target repo; refresh after a `wellman` upgrade with `python -m wellman.host_agent_sync --if-version-changed`.",
    ]
    if full_links:
        body.extend([
            "- **Core cross-cutting standards (unpinned live `main`):**",
            "  - Governance & delivery: [new-project](https://github.com/wellmanifest/new-project) · [merge](https://github.com/wellmanifest/merge) · [worktrees](https://github.com/wellmanifest/worktrees) · [ticket-lifecycle](https://github.com/wellmanifest/ticket-lifecycle) · [git-lifecycle](https://github.com/wellmanifest/git-lifecycle) · [authority-lifecycle](https://github.com/wellmanifest/authority-lifecycle) · [validation-attestation](https://github.com/wellmanifest/validation-attestation)",
            "  - Docs, logs & reports: [docs](https://github.com/wellmanifest/docs) · [logs](https://github.com/wellmanifest/logs) · [report](https://github.com/wellmanifest/report) · [usermanual](https://github.com/wellmanifest/usermanual) · [metafile](https://github.com/wellmanifest/metafile) · [ssot](https://github.com/wellmanifest/ssot)",
            "  - Autonomy, runtime & limits: [autonomy](https://github.com/wellmanifest/autonomy) · [nolimits](https://github.com/wellmanifest/nolimits) · [hostguard](https://github.com/wellmanifest/hostguard) · [session-recovery](https://github.com/wellmanifest/session-recovery) · [planfile](https://github.com/wellmanifest/planfile) · [goal](https://github.com/wellmanifest/goal) · [dockuri](https://github.com/wellmanifest/dockuri) · [wellman](https://github.com/wellmanifest/wellman)",
            "  - Security, quality & release: [secrets](https://github.com/wellmanifest/secrets) · [deployment](https://github.com/wellmanifest/deployment) · [nohardcode](https://github.com/wellmanifest/nohardcode) · [semver](https://github.com/wellmanifest/semver) · [test-poa](https://github.com/wellmanifest/test-poa) · [repair-lifecycle](https://github.com/wellmanifest/repair-lifecycle)",
        ])
    else:
        body.append(f"- **Workspace root instructions:** `{workspace_root / 'AGENTS.md'}`")
    body.append(END_MARK)
    return "\n".join(body) + "\n"


def read_synced_version(path: Path) -> str | None:
    """Return the wellman-version stamp embedded in a managed SSOT block, if present."""
    if not path.is_file():
        return None
    try:
        match = _VERSION_RE.search(path.read_text(encoding="utf-8", errors="ignore"))
    except OSError:
        return None
    return match.group(1) if match else None


def _is_in_git_repo(path: Path) -> bool:
    check_dir = path.parent
    while not check_dir.exists() and check_dir != check_dir.parent:
        check_dir = check_dir.parent
    if not check_dir.is_dir():
        return False
    res = subprocess.run(
        ["git", "-C", str(check_dir), "rev-parse", "--is-inside-work-tree"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    return res.returncode == 0


def _place_block_at_top(text: str, block: str) -> str:
    """Remove any existing SSOT block and insert the new block right after a leading H1 (or at top)."""
    cleaned = _BLOCK_RE.sub("", text)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned).strip("\n")
    if not cleaned:
        return block
    lines = cleaned.splitlines()
    if lines and lines[0].startswith("# "):
        rest = "\n".join(lines[1:]).lstrip("\n")
        if rest:
            return f"{lines[0]}\n\n{block}\n{rest}\n"
        return f"{lines[0]}\n\n{block}"
    return f"{block}\n{cleaned}\n"


def _upsert_block(
    path: Path,
    block: str,
    *,
    create_parents: bool = False,
    check_only: bool = False,
) -> str:
    if _is_in_git_repo(path):
        return "SKIP_GIT"
    if not path.parent.is_dir():
        if not create_parents:
            return "SKIP_NO_DIR"
        if not check_only:
            path.parent.mkdir(parents=True, exist_ok=True)
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    had_block = bool(_BLOCK_RE.search(text))
    new_text = _place_block_at_top(text, block)
    action = "UPDATED" if had_block else ("PREPEND" if text else "CREATED")
    if new_text == text:
        return "UNCHANGED"
    if check_only:
        return f"WOULD_{action}"
    path.write_text(new_text, encoding="utf-8")
    return action


def _sync_cursor_rule(home: Path, block: str, *, check_only: bool) -> str:
    cursor_dir = home / ".cursor" / "rules"
    if not cursor_dir.is_dir():
        return "SKIP_NO_CURSOR"
    rule_path = cursor_dir / "wellmanifest-standards-ssot.mdc"
    content = (
        "---\n"
        "description: Always resolve current WellManifest standards from live GitHub or STANDARDS.md and enforce .worktrees/ storage invariants\n"
        "alwaysApply: true\n"
        "---\n\n"
        + block
    )
    if rule_path.exists() and rule_path.read_text(encoding="utf-8") == content:
        return "UNCHANGED"
    if check_only:
        return "WOULD_WRITE"
    rule_path.write_text(content, encoding="utf-8")
    return "WRITTEN"


def _sync_aider_conf(home: Path, invariants_md: Path, *, check_only: bool) -> str:
    aider_conf = home / ".aider.conf.yml"
    target = str(invariants_md)
    if aider_conf.exists():
        text = aider_conf.read_text(encoding="utf-8")
        if target in text:
            return "UNCHANGED"
        if check_only:
            return "WOULD_UPDATE"
        aider_conf.write_text(text.rstrip() + f"\nread:\n  - {target}\n", encoding="utf-8")
        return "UPDATED"
    if check_only:
        return "WOULD_CREATE"
    aider_conf.write_text(
        "# Managed WellManifest SSOT read-only conventions for Aider\n"
        f"read:\n  - {target}\n",
        encoding="utf-8",
    )
    return "CREATED"


def sync_host_agents(
    *,
    home: Path | None = None,
    workspace_root: Path | None = None,
    wellmanifest_root: Path | None = None,
    version: str | None = None,
    if_version_changed: bool = False,
    check_only: bool = False,
) -> dict[str, Any]:
    """Synchronize live standards index and SSOT blocks across all LLM host configs."""
    resolved_home = (home or Path.home()).resolve()
    resolved_ws = (workspace_root or (resolved_home / "github")).resolve()
    resolved_wm = (wellmanifest_root or (resolved_ws / "wellmanifest")).resolve()
    resolved_ver = version or WELLMAN_VERSION

    stamp_probe = resolved_ws / "AGENTS.md"
    if not stamp_probe.is_file():
        stamp_probe = resolved_wm / "AGENT-INVARIANTS.md"
    previous_version = read_synced_version(stamp_probe)
    if if_version_changed and previous_version == resolved_ver:
        return {
            "status": "up_to_date",
            "version": resolved_ver,
            "previous_version": previous_version,
            "skipped": True,
            "targets": {},
        }

    rows = collect_standards(resolved_wm)
    full_block = build_ssot_block(
        workspace_root=resolved_ws,
        wellmanifest_root=resolved_wm,
        version=resolved_ver,
        full_links=True,
    )
    compact_block = build_ssot_block(
        workspace_root=resolved_ws,
        wellmanifest_root=resolved_wm,
        version=resolved_ver,
        full_links=False,
    )

    standards_md = resolved_wm / "STANDARDS.md"
    invariants_md = resolved_wm / "AGENT-INVARIANTS.md"
    targets: dict[str, str] = {}

    if resolved_wm.is_dir():
        new_standards = render_standards_index(rows, wellmanifest_root=resolved_wm, version=resolved_ver)
        if not standards_md.exists() or standards_md.read_text(encoding="utf-8") != new_standards:
            if check_only:
                targets[str(standards_md)] = "WOULD_WRITE"
            else:
                standards_md.write_text(new_standards, encoding="utf-8")
                targets[str(standards_md)] = "WRITTEN"
        else:
            targets[str(standards_md)] = "UNCHANGED"

        new_invariants = f"# WellManifest Agent Invariants (managed by wellman {resolved_ver})\n\n" + compact_block
        if not invariants_md.exists() or invariants_md.read_text(encoding="utf-8") != new_invariants:
            if check_only:
                targets[str(invariants_md)] = "WOULD_WRITE"
            else:
                invariants_md.write_text(new_invariants, encoding="utf-8")
                targets[str(invariants_md)] = "WRITTEN"
        else:
            targets[str(invariants_md)] = "UNCHANGED"

    full_targets = [
        resolved_ws / "AGENTS.md",
        resolved_wm / "AGENTS.md",
    ]
    compact_existing_dir_targets = [
        resolved_home / ".claude" / "CLAUDE.md",
        resolved_home / ".codex" / "AGENTS.md",
        resolved_home / ".codex-softreck" / "AGENTS.md",
        resolved_home / ".gemini" / "GEMINI.md",
        resolved_home / ".config" / "opencode" / "AGENTS.md",
        resolved_home / ".codeium" / "windsurf" / "memories" / "global_rules.md",
        resolved_home / ".copilot" / "copilot-instructions.md",
        resolved_home / ".factory" / "AGENTS.md",
    ]
    if resolved_ws.is_dir():
        for child in sorted(resolved_ws.iterdir()):
            org_agents = child / "AGENTS.md"
            if child.is_dir() and org_agents.is_file() and org_agents not in full_targets:
                compact_existing_dir_targets.append(org_agents)

    rule_targets = [
        (resolved_home / ".continue", resolved_home / ".continue" / "rules" / "wellmanifest-standards-ssot.md"),
        (resolved_home / ".cline", resolved_home / "Documents" / "Cline" / "Rules" / "wellmanifest-standards-ssot.md"),
    ]

    for target in full_targets:
        targets[str(target)] = _upsert_block(target, full_block, check_only=check_only)
    for target in compact_existing_dir_targets:
        targets[str(target)] = _upsert_block(target, compact_block, check_only=check_only)
    for marker_dir, target in rule_targets:
        if marker_dir.is_dir():
            targets[str(target)] = _upsert_block(target, compact_block, create_parents=True, check_only=check_only)
        else:
            targets[str(target)] = "SKIP_NO_DIR"

    targets[str(resolved_home / ".cursor" / "rules" / "wellmanifest-standards-ssot.mdc")] = _sync_cursor_rule(
        resolved_home, compact_block, check_only=check_only
    )
    if (resolved_home / ".aider").is_dir() or (resolved_home / ".aider.conf.yml").exists():
        targets[str(resolved_home / ".aider.conf.yml")] = _sync_aider_conf(
            resolved_home, invariants_md, check_only=check_only
        )

    changed = any(
        v in {"WRITTEN", "UPDATED", "APPENDED", "PREPEND", "CREATED"} or v.startswith("WOULD_")
        for v in targets.values()
    )
    return {
        "status": "drift_detected" if (check_only and changed) else ("synced" if changed else "up_to_date"),
        "version": resolved_ver,
        "previous_version": previous_version,
        "standards_count": len(rows),
        "skipped": False,
        "targets": targets,
    }


def maybe_auto_sync_host_agents(
    *,
    home: Path | None = None,
    workspace_root: Path | None = None,
    wellmanifest_root: Path | None = None,
    version: str | None = None,
    env: dict[str, str] | None = None,
) -> dict[str, Any] | None:
    """Automatically sync host LLM configs when wellman's version changes.

    Fail-safe no-op in CI, pytest, opt-out environments, or hosts without a
    local ``wellmanifest`` workspace directory.
    """
    active_env = os.environ if env is None else env
    for guard in ("CI", "GITHUB_ACTIONS", "PYTEST_CURRENT_TEST", "WELLMAN_NO_AUTO_HOST_SYNC"):
        val = str(active_env.get(guard, "")).strip().lower()
        if val and val not in {"0", "false", "no"}:
            return None

    resolved_home = (home or Path.home()).resolve()
    resolved_ws = (workspace_root or (resolved_home / "github")).resolve()
    resolved_wm = (wellmanifest_root or (resolved_ws / "wellmanifest")).resolve()
    if not resolved_wm.is_dir():
        return None

    try:
        return sync_host_agents(
            home=resolved_home,
            workspace_root=resolved_ws,
            wellmanifest_root=resolved_wm,
            version=version,
            if_version_changed=True,
        )
    except OSError:
        return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="wellman sync-hosts",
        description="Sync live WellManifest standards SSOT and workspace invariants across LLM host configs.",
    )
    parser.add_argument("--home", type=Path, default=None, help="Override user home directory")
    parser.add_argument("--workspace-root", type=Path, default=None, help="Override GitHub workspace root (default: ~/github)")
    parser.add_argument("--wellmanifest-root", type=Path, default=None, help="Override wellmanifest org directory")
    parser.add_argument("--if-version-changed", action="store_true", help="No-op if already synced for the current wellman version")
    parser.add_argument("--check", action="store_true", help="Report drift without writing files (exit 2 on drift)")
    parser.add_argument("--json", action="store_true", help="Emit JSON summary")
    args = parser.parse_args(argv)

    result = sync_host_agents(
        home=args.home,
        workspace_root=args.workspace_root,
        wellmanifest_root=args.wellmanifest_root,
        if_version_changed=args.if_version_changed,
        check_only=args.check,
    )
    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print(f"wellman host_agent_sync {result['version']}: {result['status']} (standards={result.get('standards_count', 0)})")
        for path, action in result["targets"].items():
            print(f"  {action:14s} {path}")
    if args.check and result["status"] == "drift_detected":
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
